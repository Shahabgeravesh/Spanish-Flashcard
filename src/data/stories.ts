export function filterStories(
  list: Story[],
  tense: Tense | 'all',
): Story[] {
  const sorted = [...list].sort((a, b) => a.night - b.night)
  if (tense === 'all') return sorted
  return sorted.filter((s) => s.tense === tense)
}

export function storyById(id: string): Story | undefined {
  return stories.find((s) => s.id === id)
}

export function nextUnreadStory(
  list: Story[],
  understoodIds: string[],
): Story | undefined {
  return [...list]
    .sort((a, b) => a.night - b.night)
    .find((s) => !understoodIds.includes(s.id))
}
